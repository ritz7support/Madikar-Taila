create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  reference_id text not null unique,
  profile_id uuid not null references public."Profile"(id) on delete restrict,
  whatsapp_user_id text not null,
  catalog_id text not null,
  status text not null default 'pending_payment' check (status in ('pending_payment','paid','confirmed','processing','shipped','delivered','cancelled')),
  currency text not null default 'INR',
  subtotal numeric(12,2) not null default 0,
  shipping numeric(12,2) not null default 0,
  discount numeric(12,2) not null default 0,
  total numeric(12,2) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_retailer_id text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  currency text not null default 'INR',
  created_at timestamptz not null default now()
);

create index if not exists orders_profile_id_idx on public.orders(profile_id);
create index if not exists orders_whatsapp_user_id_idx on public.orders(whatsapp_user_id);
create index if not exists order_items_order_id_idx on public.order_items(order_id);
create index if not exists order_items_product_retailer_id_idx on public.order_items(product_retailer_id);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;

create policy "Users can view their own orders"
on public.orders
for select
to authenticated
using ((select auth.uid()) = profile_id);

create policy "Users can view their own order items"
on public.order_items
for select
to authenticated
using (
  exists (
    select 1 from public.orders o
    where o.id = order_items.order_id
      and (select auth.uid()) = o.profile_id
  )
);

create or replace function public.set_orders_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists orders_set_updated_at on public.orders;
create trigger orders_set_updated_at
before update on public.orders
for each row execute function public.set_orders_updated_at();
