-- The existing Meta Product table is the canonical catalog for the web store too.
-- Store-only fields are ignored by the Meta sync's merge payload.
alter table public."Product" add column if not exists store_id text;
alter table public."Product" add column if not exists category text;
alter table public."Product" add column if not exists short_description text;
alter table public."Product" add column if not exists images jsonb not null default '[]'::jsonb;
alter table public."Product" add column if not exists store_sort_order integer;
alter table public."Product" add column if not exists store_active boolean not null default false;
create unique index if not exists product_store_id_key
  on public."Product"(store_id) where store_id is not null;
create unique index if not exists product_store_sort_order_key
  on public."Product"(store_sort_order) where store_sort_order is not null;
alter table public."Product" add constraint product_images_array_check check (jsonb_typeof(images) = 'array');
alter table public."Product" add constraint product_store_fields_check
  check (not store_active or (store_id ~ '^p[0-9]+$' and category is not null
    and jsonb_array_length(images) > 0));

create table if not exists public."ProductVariant" (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public."Product"(id) on delete cascade,
  position integer not null check (position >= 0),
  size text not null check (length(size) between 1 and 40),
  price numeric(10,2) not null check (price > 0),
  inventory_quantity integer check (inventory_quantity >= 0),
  availability_status text not null default 'unverified'
    check (availability_status in ('unverified', 'available', 'unavailable')),
  unique (product_id, position),
  unique (product_id, size)
);
create index if not exists product_variant_product_id_idx on public."ProductVariant"(product_id);
alter table public."ProductVariant" enable row level security;
revoke all on public."ProductVariant" from anon, authenticated;
grant select, insert, update, delete on public."ProductVariant" to service_role;
grant usage, select on sequence public."ProductVariant_id_seq" to service_role;

-- Meta's sync stays untouched. Its stale-row deletion cannot remove a store-listed product.
create or replace function public.keep_store_product_on_meta_cleanup()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  if old.store_active and old.catalog_id = '1515875913870520' then return null; end if;
  return old;
end;
$$;
create trigger keep_store_product_on_meta_cleanup
before delete on public."Product"
for each row execute function public.keep_store_product_on_meta_cleanup();
