CREATE TABLE public.payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  provider text NOT NULL DEFAULT 'razorpay',
  provider_payment_link_id text,
  provider_payment_link_reference_id text,
  provider_payment_link_url text,
  provider_payment_id text,
  provider_order_id text,
  amount numeric NOT NULL,
  currency text NOT NULL DEFAULT 'INR',
  status text NOT NULL DEFAULT 'pending',
  payment_method text,
  expires_at timestamptz,
  paid_at timestamptz,
  failed_at timestamptz,
  cancelled_at timestamptz,
  provider_event_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT payments_amount_check CHECK (amount >= 0),
  CONSTRAINT payments_status_check CHECK (status IN ('pending','processing','paid','failed','cancelled','expired','refunded','partially_refunded')),
  CONSTRAINT payments_provider_check CHECK (provider IN ('razorpay'))
);
CREATE INDEX payments_order_id_idx ON public.payments(order_id);
CREATE INDEX payments_provider_payment_link_reference_id_idx ON public.payments(provider_payment_link_reference_id);
CREATE UNIQUE INDEX payments_provider_payment_link_id_uidx ON public.payments(provider_payment_link_id) WHERE provider_payment_link_id IS NOT NULL;
CREATE UNIQUE INDEX payments_provider_payment_id_uidx ON public.payments(provider_payment_id) WHERE provider_payment_id IS NOT NULL;
CREATE UNIQUE INDEX payments_provider_event_id_uidx ON public.payments(provider_event_id) WHERE provider_event_id IS NOT NULL;
CREATE INDEX payments_order_status_idx ON public.payments(order_id, status, created_at DESC);

INSERT INTO public.payments (
  order_id, provider, provider_payment_link_id, provider_payment_link_reference_id,
  provider_payment_link_url, provider_payment_id, amount, currency, status,
  paid_at, provider_event_id, created_at, updated_at
)
SELECT
  o.id,
  'razorpay',
  o.razorpay_payment_link_id,
  o.razorpay_payment_link_reference_id,
  o.razorpay_payment_link_url,
  o.razorpay_payment_id,
  o.total,
  o.currency,
  CASE
    WHEN o.razorpay_payment_status = 'paid' THEN 'paid'
    WHEN o.razorpay_payment_status = 'created' THEN 'pending'
    ELSE 'pending'
  END,
  o.razorpay_paid_at,
  o.razorpay_event_id,
  o.created_at,
  o.updated_at
FROM public.orders o
WHERE o.razorpay_payment_link_id IS NOT NULL
   OR o.razorpay_payment_id IS NOT NULL
   OR o.razorpay_event_id IS NOT NULL;

ALTER TABLE public.orders
  DROP COLUMN razorpay_payment_link_id,
  DROP COLUMN razorpay_payment_link_reference_id,
  DROP COLUMN razorpay_payment_link_url,
  DROP COLUMN razorpay_payment_id,
  DROP COLUMN razorpay_payment_status,
  DROP COLUMN razorpay_paid_at,
  DROP COLUMN razorpay_event_id;
